SELECT BILL.CONTACT_ID,
BILL.TOTAL_AMOUNT,
BILL.METAL_BALANCE,
METAL.METAL_NAME
FROM BILL BILL
LEFT JOIN BILL_SOURCE BS
ON BILL.BILL_SOURCE_ID = BS.BILL_SOURCE_ID
LEFT JOIN METAL METAL
ON BILL.METAL_ID = METAL.METAL_ID
WHERE BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BS.BILL_SOURCE_NAME IN ('GOLD_WHOLESALE_GST')
AND (BILL.BILL_DATE BETWEEN STR_TO_DATE('01/01/2020','%d/%m/%Y') AND STR_TO_DATE('01/01/2022','%d/%m/%Y'))
;

SELECT PD.CONTACT_ID,
PD.AMOUNT_PAID,
PD.METAL_PAID,
METAL.METAL_NAME
FROM PAYMENT_DETAILS PD
LEFT JOIN BILL_SOURCE BS
ON PD.BILL_SOURCE_ID = BS.BILL_SOURCE_ID
LEFT JOIN METAL METAL
ON PD.METAL_ID = METAL.METAL_ID
WHERE PD.DELETED_FLAG='N'
AND PD.LICENCE_ID=1
AND BS.BILL_SOURCE_NAME IN ('GOLD_WHOLESALE_GST')
AND (PD.PAYMENT_DATE_TIME BETWEEN STR_TO_DATE('01/01/2020','%d/%m/%Y') AND STR_TO_DATE('01/01/2022','%d/%m/%Y'))
;


SELECT 
BALANCE_SHEET.CONTACT_ID,BALANCE_SHEET.CONTACT_NAME,
(BALANCE_SHEET.TOTAL_AMOUNT-BALANCE_SHEET.AMOUNT_PAID) AMOUNT_BALANCE,
(BALANCE_SHEET.METAL_BALANCE-BALANCE_SHEET.METAL_PAID) METAL_BALANCE,
BALANCE_SHEET.BILL_METAL_NAME
FROM(
SELECT CONTACT.CONTACT_ID,CONTACT.CONTACT_NAME,
IFNULL(BILL_DETAILS.TOTAL_AMOUNT,'0') TOTAL_AMOUNT,
IFNULL(BILL_DETAILS.METAL_BALANCE,'0') METAL_BALANCE,
BILL_DETAILS.BILL_METAL_NAME,
IFNULL(PAYMENT_DETAILS.AMOUNT_PAID,'0') AMOUNT_PAID,
IFNULL(PAYMENT_DETAILS.METAL_PAID,'0') METAL_PAID,
PAYMENT_DETAILS.METAL_NAME_PAID

FROM CONTACT CONTACT
LEFT JOIN(
SELECT BILL.CONTACT_ID,
SUM(BILL.TOTAL_AMOUNT) TOTAL_AMOUNT,
SUM(BILL.METAL_BALANCE) METAL_BALANCE,
METAL.METAL_NAME BILL_METAL_NAME
FROM BILL BILL
LEFT JOIN BILL_SOURCE BS
ON BILL.BILL_SOURCE_ID = BS.BILL_SOURCE_ID
LEFT JOIN METAL METAL
ON BILL.METAL_ID = METAL.METAL_ID
LEFT JOIN CONTACT CON
ON BILL.CONTACT_ID = CON.CONTACT_ID
LEFT JOIN CONTACT_TYPE CT
ON CON.CONTACT_TYPE_ID = CT.CONTACT_TYPE_ID

WHERE BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND CT.CONTACT_TYPE_NAME = 'SUPPLIER'
AND BS.BILL_SOURCE_NAME IN ('GOLD_WHOLESALE_GST')
AND BILL.BILL_DATE <= STR_TO_DATE('01/01/2022','%d/%m/%Y')
GROUP BY BILL.CONTACT_ID
) BILL_DETAILS
ON CONTACT.CONTACT_ID = BILL_DETAILS.CONTACT_ID
LEFT JOIN(
SELECT PD.CONTACT_ID,
SUM(PD.AMOUNT_PAID) AMOUNT_PAID,
SUM(PD.METAL_PAID) METAL_PAID,
METAL.METAL_NAME METAL_NAME_PAID
FROM PAYMENT_DETAILS PD
LEFT JOIN BILL_SOURCE BS
ON PD.BILL_SOURCE_ID = BS.BILL_SOURCE_ID
LEFT JOIN METAL METAL
ON PD.METAL_ID = METAL.METAL_ID
LEFT JOIN CONTACT CON
ON PD.CONTACT_ID = CON.CONTACT_ID
LEFT JOIN CONTACT_TYPE CT
ON CON.CONTACT_TYPE_ID = CT.CONTACT_TYPE_ID

WHERE PD.DELETED_FLAG='N'
AND PD.LICENCE_ID=1
AND CT.CONTACT_TYPE_NAME = 'SUPPLIER'
AND BS.BILL_SOURCE_NAME IN ('GOLD_WHOLESALE_GST')
AND PD.PAYMENT_DATE_TIME <= STR_TO_DATE('01/01/2022','%d/%m/%Y')
GROUP BY PD.CONTACT_ID
) PAYMENT_DETAILS
ON CONTACT.CONTACT_ID = PAYMENT_DETAILS.CONTACT_ID
JOIN CONTACT_TYPE CONTACT_TYPE
ON CONTACT.CONTACT_TYPE_ID = CONTACT_TYPE.CONTACT_TYPE_ID
WHERE CONTACT.DELETED_FLAG='N'
AND CONTACT_TYPE.CONTACT_TYPE_NAME='SUPPLIER'

)BALANCE_SHEET
GROUP BY BALANCE_SHEET.CONTACT_NAME
ORDER BY BALANCE_SHEET.CONTACT_NAME
;