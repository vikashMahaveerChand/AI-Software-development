FROM ORNAMENT ORN
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
;

SELECT ORN.ORNAMENT_ID,
OPENING.OPENING_STOCK_DETAILS_LICENCE_ID,OPENING.GRAMS
FROM ORNAMENT ORN
LEFT OUTER JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=1
;

WITH 
ORN AS (
SELECT ORN.ORNAMENT_ID,ORN.METAL_ID,ORN.ORNAMENT_NAME
FROM ORNAMENT ORN
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
),
GST_STOCK AS(
SELECT ORN.ORNAMENT_ID,
OPENING.OPENING_STOCK_DETAILS_LICENCE_ID,OPENING.GRAMS
FROM ORNAMENT ORN
LEFT OUTER JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=1
)

SELECT ORN.ORNAMENT_ID,ORN.ORNAMENT_NAME,GST_STOCK.OPENING_STOCK_DETAILS_LICENCE_ID,GST_STOCK.GRAMS
LEFT JOIN ORN.ORNAMENT_ID = GST_STOCK.ORNAMENT_ID;

--ORNAMENT STOCK ENTRY QUERY STARTS
SELECT ORN.ORNAMENT_ID,ORN.METAL_ID,ORN.ORNAMENT_NAME,ORN.ORNAMENT_CODE,ORN.GST_PERCENTAGE,ORN.PURITY,ORN.MC_RATE,ORN.MC_PER_PIECE,
GST_STOCK.OPENING_STOCK_DETAILS_LICENCE_ID GST_STOCK_ID,GST_STOCK.GRAMS GST_GRAMS,
NONGST_STOCK.OPENING_STOCK_DETAILS_LICENCE_ID NON_GST_STOCK_ID,NONGST_STOCK.GRAMS NONGST_GRAMS
FROM ORNAMENT ORN
LEFT JOIN(
SELECT ORN.ORNAMENT_ID,
OPENING.OPENING_STOCK_DETAILS_LICENCE_ID,OPENING.GRAMS
FROM ORNAMENT ORN
LEFT OUTER JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
LEFT JOIN BILL_TYPE BT
ON OPENING.BILL_TYPE_ID = BT.BILL_TYPE_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
--AND OPENING.BILL_TYPE_ID=1
AND BT.BILL_TYPE_NAME = 'GST'
)GST_STOCK
ON ORN.ORNAMENT_ID = GST_STOCK.ORNAMENT_ID
LEFT JOIN(
SELECT ORN.ORNAMENT_ID,
OPENING.OPENING_STOCK_DETAILS_LICENCE_ID,OPENING.GRAMS
FROM ORNAMENT ORN
LEFT OUTER JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
LEFT JOIN BILL_TYPE BT
ON OPENING.BILL_TYPE_ID = BT.BILL_TYPE_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
--AND OPENING.BILL_TYPE_ID=2
AND BT.BILL_TYPE_NAME = 'NON_GST'
)NONGST_STOCK
ON ORN.ORNAMENT_ID = NONGST_STOCK.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
;
--ORNAMENT STOCK ENTRY QUERY ENDS

--GST SALE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT)
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (1,3,9,11)
GROUP BY BD.ORNAMENT_ID
--GST SALE ENDS
;

--NONGST SALE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT)
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (2,4,10,12)
GROUP BY BD.ORNAMENT_ID
--NONGST SALE ENDS
;

--GST PURCHASE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT)
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (5,7)
GROUP BY BD.ORNAMENT_ID
--GST PURCHASE ENDS
;

--NONGST PURCHASE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT)
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (6,8)
GROUP BY BD.ORNAMENT_ID
--NONGST PURCHASE ENDS
;

--GST OPENING STOCK STARTS
SELECT ORN.ORNAMENT_ID,OPENING.GRAMS
FROM ORNAMENT ORN
JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=1
;
--GST OPENING STOCK ENDS

--NONGST OPENING STOCK STARTS
SELECT ORN.ORNAMENT_ID,OPENING.GRAMS
FROM ORNAMENT ORN
JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=2
;
--NONGST OPENING STOCK ENDS


--STOCK QUERY STARTS
SELECT ORNAMENT_ID ORN_ID,ORNAMENT_NAME ORN_NAME,
GST_OPENING_STOCK,NONGST_OPENING_STOCK,
GST_SALE,NONGST_SALE,
GST_PURCHASE,NONGST_PURCHASE,
(SUM(IFNULL(GST_OPENING_STOCK,0))+SUM(IFNULL(GST_PURCHASE,0))-SUM(IFNULL(GST_SALE,0))) GSTSTOCK,
(SUM(IFNULL(NONGST_OPENING_STOCK,0))+SUM(IFNULL(NONGST_PURCHASE,0))-SUM(IFNULL(NONGST_SALE,0))) NONGSTSTOCK
FROM(
SELECT ORN.ORNAMENT_ID,ORN.ORNAMENT_NAME,
GST_OPENING_STOCK.GRAMS GST_OPENING_STOCK,
NONGST_OPENING_STOCK.GRAMS NONGST_OPENING_STOCK,
GST_SALE.GRAMS GST_SALE,
NONGST_SALE.GRAMS NONGST_SALE,
GST_PURCHASE.GRAMS GST_PURCHASE,
NONGST_PURCHASE.GRAMS NONGST_PURCHASE
FROM ORNAMENT ORN
LEFT JOIN(
--GST OPENING STOCK STARTS
SELECT ORN.ORNAMENT_ID,OPENING.GRAMS
FROM ORNAMENT ORN
JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=1
--GST OPENING STOCK ENDS
)GST_OPENING_STOCK
ON ORN.ORNAMENT_ID = GST_OPENING_STOCK.ORNAMENT_ID

LEFT JOIN(
--NONGST OPENING STOCK STARTS
SELECT ORN.ORNAMENT_ID,OPENING.GRAMS
FROM ORNAMENT ORN
JOIN OPENING_STOCK_DETAILS_LICENCE OPENING
ON ORN.ORNAMENT_ID = OPENING.ORNAMENT_ID
WHERE 0=0
AND ORN.DELETED_FLAG='N'
AND ORN.LICENCE_ID = 1
AND OPENING.DELETED_FLAG='N'
AND OPENING.LICENCE_ID=1
AND OPENING.BILL_TYPE_ID=2
--NONGST OPENING STOCK ENDS
)NONGST_OPENING_STOCK
ON ORN.ORNAMENT_ID = NONGST_OPENING_STOCK.ORNAMENT_ID

LEFT JOIN(
--GST SALE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT) GRAMS
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (1,3,9,11)
GROUP BY BD.ORNAMENT_ID
--GST SALE ENDS
)GST_SALE
ON ORN.ORNAMENT_ID = GST_SALE.ORNAMENT_ID

LEFT JOIN(
--NONGST SALE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT) GRAMS
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (2,4,10,12)
GROUP BY BD.ORNAMENT_ID
--NONGST SALE ENDS
)NONGST_SALE
ON ORN.ORNAMENT_ID = NONGST_SALE.ORNAMENT_ID

LEFT JOIN(
--GST PURCHASE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT) GRAMS
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (5,7)
AND (BILL.BILL_DATE BETWEEN STR_TO_DATE('01/01/2020','%d/%m/%Y') AND STR_TO_DATE('01/01/2022','%d/%m/%Y'))
GROUP BY BD.ORNAMENT_ID
--GST PURCHASE ENDS
)GST_PURCHASE
ON ORN.ORNAMENT_ID = GST_PURCHASE.ORNAMENT_ID

LEFT JOIN(
--NONGST PURCHASE STARTS
SELECT BD.ORNAMENT_ID,SUM(BD.WEIGHT) GRAMS
FROM BILL_DETAILS BD
JOIN BILL BILL
ON BD.BILL_ID = BILL.BILL_ID
WHERE 0=0
AND BILL.DELETED_FLAG='N'
AND BILL.LICENCE_ID=1
AND BILL.BILL_SOURCE_ID IN (6,8)
AND (BILL.BILL_DATE BETWEEN STR_TO_DATE('01/01/2020','%d/%m/%Y') AND STR_TO_DATE('01/01/2022','%d/%m/%Y'))
GROUP BY BD.ORNAMENT_ID
--NONGST PURCHASE ENDS
)NONGST_PURCHASE
ON ORN.ORNAMENT_ID = NONGST_PURCHASE.ORNAMENT_ID
) ORNAMENT_STOCK
GROUP BY ORNAMENT_ID
ORDER BY ORN_NAME ASC
;
--STOCK QUERY ENDS

